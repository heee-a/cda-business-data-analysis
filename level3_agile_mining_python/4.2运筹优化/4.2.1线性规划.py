# ============================================================
# ### 线性规划
# ============================================================

# ============================================================
# 模型样例
# ============================================================

# ============================================================
#
# Objective function:
#
#  Maximize $x_1 + 2 x_2 + 3 x_3 + x_4$
#
# ============================================================

# ============================================================
# Subject To
#
#  r1: $- x_1 + x_2 + x_3 + 10 x_4 <= 20$
#
#  r2: $x_1 - 3 x_2 + x_3 <= 30$
#
#  r3: $x_2 - 3.5 x_4  = 0$
# ============================================================

# ============================================================
# Bounds
#
#  $0 <= x_1 <= 40$
#
#  $2 <= x_4 <= 3$
# ============================================================

# ============================================================
# 导入CPLEX
# ============================================================

# --- code cell ---
import cplex

# ============================================================
# 初始化模型
# ============================================================

# --- code cell ---
op = cplex.Cplex()

# ============================================================
# 读取lp文件
# ============================================================

# --- code cell ---
op.read("productivity.lp")

# ============================================================
# 模型求解
# ============================================================

# --- code cell ---
op.solve()

# --- code cell ---
print("Max objective value is %s" %op.solution.get_objective_value())
print("Best Productivety is %s" %op.solution.get_values())

