import cplex
import numpy as np

# ============================================================
# 初始化模型
# ============================================================

# --- code cell ---
op = cplex.Cplex()

# ============================================================
# 读取lp文件
# ============================================================

# --- code cell ---
op.read("campaign.lp")

# ============================================================
# 模型求解
# ============================================================

# --- code cell ---
op.solve()

# --- code cell ---
print("Max objective value is %s" %op.solution.get_objective_value())
print("Best allocation :")
print(np.array(op.solution.get_values()).reshape([3,-1]).T)

